# Пример 2
# +79261234567
# 79261234567
# 89261234567
# 9261234567
# +7 926 123 45 67
# +7-926-123-45-67

data='9261234567 +79261234567 79261234567 89261234567 +7 926 123 45 67 +7-926-123-45-67'
pattern=r'((\+7|7|8)?((\s|-)?\d{3}){2}((\s|-)?\d{2}){2})'
matches=[match.group() for match in finditer(pattern,data)]
print(*matches)
