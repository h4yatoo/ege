# Метасимволы
# . - ровно один любой символ;
# \d - любая цифра;
# \D - любая не цифра
# \s - любой пробельный символ (пробел, tab, \n, \r);
# \S - любой не пробельный символ
# \w - любая буква, цифра или _;

# Диапазоны символов
# [02468] - ровно один любой символ из указанного набора;
# [a-h] - диапазон символов по алфавиту от и до;
# [1-7A-K];
# [^50] - символы не из заданного набора
# [а-яё] - кириллица;

# Квантификторы
# позволяют задать кол-во встреч символов
# {m,n} - кол-во повторений от m до n штук;
# + / {1,} - хотя бы одно вхождение;
# * / {0,} - любове кол-во вхождений;
# ? / {0,1} - либо 0, либо 1 раз;

# Скобочные группы
# (\+7|7|8) - позволяет сгруппировать символы и выбрать один из вариантов;

